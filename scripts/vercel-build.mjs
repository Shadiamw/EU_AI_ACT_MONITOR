#!/usr/bin/env node
/**
 * Copy the console UI into web/ and inject API_BASE_URL for a Vercel static deploy.
 * The API/worker/Postgres cannot run on Vercel; they stay on Docker (or a tunnel).
 */
import { cpSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "app", "static");
const out = join(root, "web");
const api = (process.env.API_BASE_URL || "").replace(/\/$/, "");

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
cpSync(src, out, { recursive: true });
writeFileSync(
  join(out, "config.js"),
  `/* Generated by scripts/vercel-build.mjs */\nwindow.__EU_MONITOR_API__ = ${JSON.stringify(api)};\n`,
  "utf8",
);

console.log(`vercel UI ready in web/ (API_BASE_URL=${api || "(same-origin / unset)"})`);
